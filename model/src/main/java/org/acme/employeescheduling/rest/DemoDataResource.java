package org.acme.employeescheduling.rest;

import java.util.List;

import jakarta.inject.Inject;
import jakarta.ws.rs.GET;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.PathParam;
import jakarta.ws.rs.Produces;
import jakarta.ws.rs.core.MediaType;

import org.eclipse.microprofile.openapi.annotations.Operation;
import org.eclipse.microprofile.openapi.annotations.tags.Tag;

@Tag(name = "Demo data", description = "Synthetic scenarios generated by data-gen.")
@Path("demo-data")
public class DemoDataResource {

    private final ScenarioRepository scenarios;

    @Inject
    public DemoDataResource(ScenarioRepository scenarios) {
        this.scenarios = scenarios;
    }

    @Operation(summary = "List scenario names (the *.json files in app.data-dir, without extension).")
    @GET
    @Produces(MediaType.APPLICATION_JSON)
    public List<String> list() {
        return scenarios.names();
    }

    @Operation(summary = "Return one unsolved scenario as WorkSchedule JSON.")
    @GET
    @Path("{name}")
    @Produces(MediaType.APPLICATION_JSON)
    public String get(@PathParam("name") String name) {
        return scenarios.raw(name);
    }
}
